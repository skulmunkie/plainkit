// Family B: Blazor and Razor only (design section 2.6, issue #518 A-9). Every other family's markup rules
// (S, D, T, A, P) already run against .razor/.cshtml through the same tolerant HTML/Razor tokenizer
// (core/tools/strict/scanners/html.mjs, design section 4.1/7: `@* *@` comments, `@{ }`/`@( )` blocks and bare
// `@expr` are skipped as opaque, `Pk*`/uppercase tags are recognised as components) - there is no separate
// "Razor scanner" module to write, the scanner already is Razor-aware. B rules exist only where the Blazor
// surface differs from plain HTML/JS: a raw tag versus a `Pk*` component, a component's own parameters, and a
// couple of Razor-only syntax shapes (`@onclick`, `MarkupString`, `@page`/`@inherits`).
//
// Data source: BLAZOR_COMPONENTS (core/tools/audit/hints.mjs, generated by core/tools/audit/data.mjs from
// blazor/mappings/*.json - the same file scripts/generate-blazor.mjs and the Blazor skill already read), keyed
// by pk-* tag with `{ component, params[] }`. B3 also needs the reverse lookup (component name -> params),
// built once below from the same table - no new source, per the design's "nothing is invented" rule (section 3).
import { scanHtml } from '../../strict/scanners/html.mjs';
import { hitsForEach, hitAt, fileIs, RAZOR_EXTENSIONS } from '../util.mjs';
import { BLAZOR_COMPONENTS } from '../hints.mjs';

const isRazor = file => fileIs(file, RAZOR_EXTENSIONS);
const isPkComponent = name => /^Pk[A-Z]/.test(name);

// Reverse of BLAZOR_COMPONENTS (tag -> {component, params}): component name -> params[], for B3.
const PARAMS_BY_COMPONENT = Object.fromEntries(Object.values(BLAZOR_COMPONENTS).map(v => [v.component, v.params]));

// Framework/passthrough attributes every component accepts regardless of its own params (design section 7:
// "an attribute that is not a parameter ... is put on the element as it is"), so B3 never flags these as an
// unknown parameter - B2 already covers Class/Style on its own.
const PASSTHROUGH_ATTRS = new Set(['Class', 'Style', 'id', 'key']);

// A generic component's own type parameter (`TItem="OrderRow"`, `TValue="int"`, `TKey="Guid"` ...): Blazor's
// naming convention for these is a leading `T` then an uppercase letter (`@typeparam TItem`), and they are not
// declared in the component's own `params` list (that list is its [Parameter] properties, not its generics) -
// so without this, every generic component usage was flagged as an "unknown parameter" (issue #686, B3).
const isTypeParam = name => /^T[A-Z]\w*$/.test(name);

// Global HTML attributes a component forwards through PkElementBase.AdditionalAttributes (unmatched attributes
// land on the element), so they are never "unknown parameters" (#1611). Compared lower-case. Not names a
// consumer mistypes for a parameter (`Label` stays flagged).
const HTML_PASSTHROUGH = new Set(['class', 'style', 'id', 'key', 'title', 'slot', 'lang', 'dir', 'hidden', 'tabindex', 'role', 'spellcheck',
    'autocapitalize', 'autocomplete', 'autofocus', 'inputmode', 'enterkeyhint', 'draggable', 'translate', 'contenteditable', 'part', 'is', 'name']);

// Blazor matches parameter names case-insensitively, and `<Param>Changed` is the two-way binding callback.
const isParam = (params, name) => {
    const lower = new Set(params.map(p => p.toLowerCase()));
    const n = name.toLowerCase();
    return lower.has(n) || (n.endsWith('changed') && lower.has(n.slice(0, -'changed'.length)));
};

// B8: a [Parameter]/[CascadingParameter] auto-property in a .razor @code block or a .cs file; the overlap is
// shared names over the larger of the two parameter lists, with at least two shared so a lone Label never fires.
const B8_PARAM = /\[(?:Parameter|CascadingParameter)\b[^\]]*\]\s*(?:\[[^\]]+\]\s*)*public\s+[^;{=()]+?\s+(\w+)\s*\{/g;
const B8_THRESHOLD = 0.8;
const B8_MIN_MATCHED = 2;

// B5's JS-interop hint table (D7's counterpart, design section 2.6): an IJSRuntime call by string name that
// duplicates behaviour a component already owns. Hand-written like D7's own API_PATTERNS (core/tools/audit/
// hints.mjs) - these are Blazor interop call names, not an element catalogue field.
const INTEROP_HINTS = [
    { re: /\.showModal\b/, api: 'showModal', element: 'pk-dialog' },
    { re: /\bclipboard\.writeText\b/, api: 'clipboard.writeText', element: 'pk-copy-button (or the clipboard-aware element you are copying from)' },
    { re: /\b(disableBodyScroll|enableBodyScroll|scrollLock|lockScroll)\b/, api: 'a manual scroll lock', element: 'pk-dialog/pk-drawer (they already lock body scroll while open)' },
];

// B1 was removed (issue #686): it reimplemented D1 ("a raw tag that has a pk-* equivalent", d-rules.mjs) under
// a new id. D1's `applies: isMarkup` already covers .razor/.cshtml (MARKUP_EXTENSIONS includes both, util.mjs),
// so every B1 finding was a byte-for-byte duplicate of a D1 finding on the same file:line - nothing B1 added.

export const B_RULES = [
    {
        id: 'B2',
        category: 'B',
        detects: 'class=/style= on markup, or Class/Style on a Pk* component (S1-S3 counterpart)',
        severity: { normal: 'warn', strict: 'error' },
        docs: 'docs/superpowers/specs/2026-09-28-conformance-audit-cli-design.md#26-family-b-blazor-and-razor-only',
        fixTemplate: 'FIX: {file}:{line} sets {found} on {component}. Use the component\'s own parameters instead of styling it from outside. [B2]',
        applies: isRazor,
        scan(file) {
            const { nodes } = scanHtml(file.text);
            const hits = [];
            for (const node of nodes) {
                if (node.closing || !isPkComponent(node.name)) continue;
                for (const attr of ['Class', 'Style']) {
                    if (node.attrs[attr] === undefined) continue;
                    hits.push({ line: node.line, column: node.column, message: `${attr}=`, found: `${attr}=`, component: `<${node.name}>` });
                }
            }
            return hits;
        },
    },
    {
        id: 'B3',
        category: 'B',
        detects: 'an unknown Pk* component, or an unknown parameter on a known one (typo or removed parameter)',
        severity: { normal: 'error', strict: 'error' },
        docs: 'docs/superpowers/specs/2026-09-28-conformance-audit-cli-design.md#26-family-b-blazor-and-razor-only',
        fixTemplate: 'FIX: {file}:{line} {found}. [B3]',
        applies: isRazor,
        scan(file) {
            const { nodes } = scanHtml(file.text);
            const hits = [];
            for (const node of nodes) {
                if (node.closing || !isPkComponent(node.name)) continue;
                const params = PARAMS_BY_COMPONENT[node.name];
                if (!params) {
                    hits.push({ line: node.line, column: node.column, message: `<${node.name}>`, found: `<${node.name}> is not a known PlainKit component (check the spelling, or it does not exist)` });
                    continue;
                }
                for (const attrName of Object.keys(node.attrs)) {
                    if (PASSTHROUGH_ATTRS.has(attrName) || HTML_PASSTHROUGH.has(attrName.toLowerCase()) || attrName.startsWith('data-') || attrName.startsWith('aria-') || isTypeParam(attrName)) continue;
                    if (!isParam(params, attrName)) {
                        hits.push({ line: node.line, column: node.column, message: `${attrName}=`, found: `<${node.name} ${attrName}=...> - ${attrName} is not a parameter of ${node.name} (check the spelling, or it was removed)` });
                    }
                }
            }
            return hits;
        },
    },
    {
        id: 'B4',
        category: 'B',
        detects: 'a @page component that does not derive from the SDK\'s page base',
        severity: { normal: 'warn', strict: 'warn' },
        docs: 'docs/superpowers/specs/2026-09-28-conformance-audit-cli-design.md#26-family-b-blazor-and-razor-only',
        fixTemplate: 'FIX: {file}:{line} {found}. [B4]',
        // App-wide gate (issue #718): B4 checks whether a @page component derives from PageBase, but that is
        // only a real gap when the app has actually opted into PageBase in the first place. Per the SDK's own
        // guide (core/site/guides/content/build-an-app.md, "Blazor has no app framework surface yet: a Blazor
        // app keeps PkAppShell, PageBase and the router") PageBase - not mountApp/defineModule, which are the
        // JS-only app framework - is the real, unambiguous Blazor signal: an app that has adopted it has, by
        // definition, at least one component somewhere that already declares `@inherits ...PageBase`. An app
        // that has never done that once has made no visible commitment to the convention at all (issue #686:
        // 92/92 findings against an app with its own, different, working page-lifecycle pattern), so firing on
        // every one of its pages is not "you missed this," it is restating that the app does something else.
        // This is evaluated once for the whole run (`appliesToRun`), not guessed per file.
        appliesToRun: files => files.some(f => isRazor(f) && /@inherits\s+\S*PageBase\b/.test(f.text)),
        applies: isRazor,
        scan(file) {
            if (!/@page\b/.test(file.text)) return [];
            if (/@inherits\s+\S*PageBase\b/.test(file.text)) return [];
            const m = /@page\b[^\r\n]*/.exec(file.text);
            return [hitAt(file.text, m.index, '@page', { found: 'this @page component has no @inherits ...PageBase - the app framework\'s page lifecycle (loading/error/empty states) will not run' })];
        },
    },
    {
        id: 'B5',
        category: 'B',
        detects: 'JS interop for a behaviour a component already owns (a hint, never an error: D7\'s Blazor counterpart)',
        severity: { normal: 'warn', strict: 'warn' },
        docs: 'docs/superpowers/specs/2026-09-28-conformance-audit-cli-design.md#26-family-b-blazor-and-razor-only',
        fixTemplate: 'FIX: {file}:{line} calls IJSRuntime for {api}. {element} already owns this; check whether it covers your case before keeping the interop call. [B5]',
        applies: isRazor,
        scan(file) {
            const hits = [];
            for (const { re, api, element } of INTEROP_HINTS) {
                hits.push(...hitsForEach(file.text, new RegExp(re.source, 'g'), m => hitAt(file.text, m.index, api, { found: api, api, element })));
            }
            return hits;
        },
    },
    {
        id: 'B6',
        category: 'B',
        detects: 'a <script> tag, an inline onclick on a non-component tag, or a MarkupString built from a non-literal value',
        severity: { normal: 'warn', strict: 'error' },
        docs: 'docs/superpowers/specs/2026-09-28-conformance-audit-cli-design.md#26-family-b-blazor-and-razor-only',
        fixTemplate: 'FIX: {file}:{line} {found}. [B6]',
        applies: isRazor,
        scan(file) {
            const { nodes } = scanHtml(file.text);
            const hits = [];
            // The root document component (the one holding the html and body tags) is the only place the boot script and
            // fingerprinted Assets scripts can live (#1671).
            const isRootDocument = /<html\b/i.test(file.text) && /<body\b/i.test(file.text);
            for (const node of nodes) {
                if (node.closing) continue;
                if (node.name.toLowerCase() === 'script') {
                    const src = String(node.attrs.src ?? '');
                    if (isRootDocument && /Assets\s*\[|^_framework\//.test(src)) continue;
                    hits.push({ line: node.line, column: node.column, message: '<script>', found: '<script> element in Razor markup - use a PlainKit element or its documented API instead of hand-written script' });
                }
                // An anchor whose onclick only cancels navigation, or whose href is a javascript: bookmarklet the user
                // drags to the bookmarks bar, is intentional (#1671).
                const cancelsOnly = node.name.toLowerCase() === 'a' && (/^\s*(?:return\s+false|event\.preventDefault\(\))\s*;?\s*$/.test(String(node.attrs.onclick ?? '')) || /^\s*javascript:/i.test(String(node.attrs.href ?? '')));
                if (!isPkComponent(node.name) && node.attrs.onclick !== undefined && !cancelsOnly) {
                    hits.push({ line: node.line, column: node.column, message: `<${node.name} onclick>`, found: `<${node.name}> has an inline onclick; use @onclick on a real interactive element or compose a pk-* one` });
                }
            }
            hits.push(...hitsForEach(file.text, /new\s+MarkupString\s*\(\s*(?!["'`])([^)]+)\)/g, m => hitAt(file.text, m.index, 'MarkupString', { found: `new MarkupString(${m[1].trim()}) from a non-literal value - unsanitised markup can inject script` })));
            hits.push(...hitsForEach(file.text, /\(MarkupString\)\s*([A-Za-z_][\w.]*)/g, m => hitAt(file.text, m.index, 'MarkupString', { found: `(MarkupString)${m[1]} cast from a non-literal value - unsanitised markup can inject script` })));
            return hits;
        },
    },
    {
        id: 'B7',
        category: 'B',
        detects: 'hand-rolled lifecycle plumbing in a component: IDisposable/IAsyncDisposable + CancellationTokenSource, or busy/error fields beside OnInitializedAsync, without PageBase/PkComponentBase',
        severity: { normal: 'warn', strict: 'warn' },
        docs: 'docs/superpowers/specs/2026-10-11-page-base-design.md#34-audit',
        fixTemplate: 'FIX: {file}:{line} {found}. Inherit PageBase (a page) or PkComponentBase (any other component) and override OnLoadAsync: they own cancel-on-navigation, busy/error, safe StateHasChanged after disposal and disposal. [B7]',
        applies: file => isRazor(file) || fileIs(file, ['.cs']),
        scan(file) {
            const t = file.text;
            if (/@inherits\s+(?:[\w.]+\.)?(?:PageBase|PkComponentBase)\b|:\s*(?:[\w.]+\.)?(?:PageBase|PkComponentBase)\b/.test(t)) return [];
            const cts = /\bnew\s+CancellationTokenSource\b|\bCancellationTokenSource\??\s+_?\w+/.exec(t);
            if (cts && /\bI(?:Async)?Disposable\b/.test(t)) {
                return [hitAt(t, cts.index, 'CancellationTokenSource', { found: 'hand-rolls disposal and a CancellationTokenSource' })];
            }
            const init = /\bOnInitializedAsync\b/.exec(t);
            const flag = name => new RegExp(String.raw`\b(?:bool|string\??|Exception\??)\s+_?(?:${name})\b`, 'i').test(t);
            if (init && flag('busy|isBusy|loading|isLoading|saving') && flag('error|errorMessage|loadError')) {
                return [hitAt(t, init.index, 'OnInitializedAsync', { found: 'hand-rolls busy and error fields around OnInitializedAsync' })];
            }
            return [];
        },
    },
    {
        id: 'B8',
        category: 'B',
        detects: 'a hand-written component whose [Parameter] names overlap an existing Pk* component by 80% or more (a probable duplicate, #653)',
        severity: { normal: 'warn', strict: 'warn' },
        docs: 'docs/superpowers/specs/2026-09-29-duplicate-component-detection-design.md',
        fixTemplate: 'FIX: {file}:{line} {found}. [B8]',
        applies: file => isRazor(file) || fileIs(file, ['.cs']),
        scan(file) {
            const t = file.text;
            const decls = [...t.matchAll(B8_PARAM)];
            const own = [...new Set(decls.map(m => m[1]))];
            if (own.length < B8_MIN_MATCHED) return [];
            let best = null;
            for (const [component, params] of Object.entries(PARAMS_BY_COMPONENT)) {
                const matched = own.filter(n => params.includes(n)).length;
                if (matched < B8_MIN_MATCHED) continue;
                const score = matched / Math.max(own.length, params.length);
                if (score >= B8_THRESHOLD && (!best || score > best.score)) best = { component, score, matched };
            }
            if (!best) return [];
            const pct = Math.round(best.score * 100);
            return [hitAt(t, decls[0].index, '[Parameter]', { found: `declares ${own.join(', ')}: a ${pct}% match for ${best.component}'s parameters (${best.matched} shared). Consider using <${best.component}> instead of this component` })];
        },
    },
];
