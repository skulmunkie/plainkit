// Exports the agent skills bundle (scripts/build-skills.mjs) in formats for developer agents that are not Claude Code (issue #36): a single
// top-level core/dist/AGENTS.md, and an llms.txt / llms-full.txt pair (the https://llmstxt.org convention), served from the Pages site under
// dist/ the same way dist/skills/ already is. Node only, no dependencies.
//
//   node scripts/build-agent-refs.mjs           write core/dist/AGENTS.md, core/dist/llms.txt, core/dist/llms-full.txt
//   node scripts/build-agent-refs.mjs --check   change nothing; exit 1 when they are stale (CI)
//
// Nothing here re-derives the element API, the Blazor mappings or the gallery data: every file is assembled from the exact bundle
// scripts/build-skills.mjs already builds (collect() + generate()), the single source of truth for both formats. One version, from
// core/VERSION, stamped the same way the skills are; no separate versioning (issue #35).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collect, generate, crlf, parseFrontmatter, FRONTMATTER, SKILL_NAMES } from './build-skills.mjs';
import { build } from '../core/tools/build.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const root = path.resolve(here, '..');
const core = path.join(root, 'core');
const GENERATOR = 'scripts/build-agent-refs.mjs';
export const OUT_DIR = path.join(core, 'dist');
export const OUT_NAMES = ['AGENTS.md', 'llms.txt', 'llms-full.txt'];

const lf = s => s.replace(/\r\n/g, '\n');
const HEADING = /^(#{1,6})(\s.*)$/;

/** Every heading in `text` shifted `by` levels deeper (capped at h6). */
function demote(text, by) {
    return lf(text).split('\n').map(l => { const m = HEADING.exec(l); return m ? `${'#'.repeat(Math.min(6, m[1].length + by))}${m[2]}` : l; }).join('\n');
}

/** { title, body }: the text's first `# ` heading (without the `#`) and everything after it, trimmed. */
function splitFirstHeading(text) {
    const lines = lf(text).split('\n');
    const i = lines.findIndex(l => /^#\s/.test(l));
    if (i < 0) return { title: '', body: text.trim() };
    return { title: lines[i].replace(/^#\s+/, '').trim(), body: lines.slice(i + 1).join('\n').trim() };
}

/** The first sentence of `text`, flattened to plain text and capped at 160 characters. */
function firstSentence(text) {
    const flat = String(text).replace(/[`*]/g, '').replace(/^-\s*/, '').replace(/\s+/g, ' ').trim();
    const m = /^(.+?[.!?])(\s|$)/.exec(flat);
    const s = m ? m[1] : flat;
    return s.length > 160 ? `${s.slice(0, 159).trimEnd()}…` : s;
}

// A file-wide boilerplate lead line (the same on every file of its kind, from build-skills.mjs's own fixed intros): not useful as a one-line
// description, so an index entry skips past it to the next paragraph.
const BOILERPLATE_LEAD = /^Every (element|component) (also takes|renders)\b/;

/** A short, one-line description of a generated reference file: the first sentence of its body, after the title, any "Generated by" stamp line and any boilerplate lead line. */
function summarize(text) {
    const { title, body } = splitFirstHeading(text);
    const line = lf(body).split('\n').find(l => l.trim() && !l.startsWith('> Plainkit') && !/^Plainkit [\w.-]+\. Generated by/.test(l.trim()) && !BOILERPLATE_LEAD.test(l.trim()) && !HEADING.test(l));
    return line ? firstSentence(line) : title;
}

/** The bundle's files for one skill, SKILL.md first, then its references in file order (stable: sorted by path). */
function skillFiles(bundle, skill) {
    const all = [...bundle].filter(([f]) => f.startsWith(`${skill}/`)).sort(([a], [b]) => a.localeCompare(b));
    const skillMd = all.find(([f]) => f.endsWith('/SKILL.md'));
    const refs = all.filter(([f]) => f !== skillMd[0]);
    return { skillMd, refs };
}

// ---------------------------------------------------------------- AGENTS.md

function agentsMd(src, bundle) {
    const version = src.version;
    const out = [
        '# Plainkit: agent reference', '',
        `> Plainkit ${version}. Generated by ${GENERATOR} from the same sources as the plainkit-sdk and plainkit-blazor skills (scripts/build-skills.mjs). Do not edit: change the source and run the generator.`, '',
        'Plainkit is a dependency-free UI toolkit: `pk-*` custom elements, CSS tokens and small ES modules for plain HTML pages with no framework and no build step, plus a Blazor component wrapper (`PlainKit.Blazor`). This file is a self-contained reference for a developer agent that does not read the Claude Code skill format (`SKILL.md` plus `references/`): everything below is the same generated content as the `plainkit-sdk` and `plainkit-blazor` skills, in one document. A concise index with links to the same files is `llms.txt`; a flatter full-text dump is `llms-full.txt`.', '',
    ];
    for (const skill of SKILL_NAMES) {
        const { skillMd, refs } = skillFiles(bundle, skill);
        const [, skillText] = skillMd;
        const fm = parseFrontmatter(skillText);
        const { title, body } = splitFirstHeading(skillText.replace(FRONTMATTER, ''));
        out.push(`## ${skill}`, '', fm.description, '', `### ${title}`, '', demote(body, 2), '');
        for (const [f, text] of refs) {
            const rel = f.slice(skill.length + 1);
            const { title: refTitle, body: refBody } = splitFirstHeading(text);
            out.push(`### ${rel}: ${refTitle}`, '', demote(refBody, 2), '');
        }
    }
    return out.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

// ---------------------------------------------------------------- llms.txt / llms-full.txt

function llmsTxt(src, bundle) {
    const version = src.version;
    const out = [
        '# Plainkit', '',
        `> Plainkit ${version}. A dependency-free UI toolkit: \`pk-*\` custom elements, CSS tokens and small ES modules for plain HTML pages with no framework and no build step, plus a Blazor component wrapper (PlainKit.Blazor).`, '',
        'Everything in one file: [AGENTS.md](AGENTS.md) (a single-document reference) or [llms-full.txt](llms-full.txt) (the same content, concatenated plainly). Claude Code loads the skills directly: `skills/plainkit-sdk/SKILL.md`, `skills/plainkit-blazor/SKILL.md`.', '',
    ];
    for (const skill of SKILL_NAMES) {
        const { skillMd, refs } = skillFiles(bundle, skill);
        const [, skillText] = skillMd;
        const fm = parseFrontmatter(skillText);
        out.push(`## ${skill}`, '', `- [SKILL.md](skills/${skill}/SKILL.md): ${firstSentence(fm.description)}`);
        for (const [f, text] of refs) { const rel = f.slice(skill.length + 1); out.push(`- [${rel}](skills/${f}): ${summarize(text)}`); }
        out.push('');
    }
    return out.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

function llmsFullTxt(src, bundle) {
    const version = src.version;
    const parts = [`# Plainkit\n\n> Plainkit ${version}. Generated by ${GENERATOR}; do not edit.\n`];
    for (const skill of SKILL_NAMES) {
        const { skillMd, refs } = skillFiles(bundle, skill);
        parts.push(lf(skillMd[1]).replace(FRONTMATTER, `# ${skill}\n\n`).trim());
        for (const [, text] of refs) parts.push(lf(text).trim());
    }
    return parts.join('\n\n---\n\n').trim() + '\n';
}

// ---------------------------------------------------------------- entry points

export function generateAll(src = collect()) {
    const bundle = generate(src);
    return new Map([
        ['AGENTS.md', agentsMd(src, bundle)],
        ['llms.txt', llmsTxt(src, bundle)],
        ['llms-full.txt', llmsFullTxt(src, bundle)],
    ]);
}

export function diskFiles(dir = OUT_DIR) {
    const out = new Map();
    for (const name of OUT_NAMES) { const f = path.join(dir, name); if (fs.existsSync(f)) out.set(name, fs.readFileSync(f, 'utf8')); }
    return out;
}

export function differences(gen = generateAll(), dir = OUT_DIR) {
    const disk = diskFiles(dir);
    const d = [];
    for (const [f, text] of gen) { if (!disk.has(f)) d.push(`missing: ${f}`); else if (disk.get(f) !== crlf(text)) d.push(`changed: ${f}`); }
    for (const f of disk.keys()) if (!gen.has(f)) d.push(`extra: ${f}`);
    return d.sort();
}

export function write(gen = generateAll(), dir = OUT_DIR) {
    fs.mkdirSync(dir, { recursive: true });
    for (const [f, text] of gen) fs.writeFileSync(path.join(dir, f), crlf(text));
    return gen.size;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    let gen;
    try { gen = generateAll(); } catch (e) { console.error(`build-agent-refs: ${e.message}`); process.exit(2); }
    if (process.argv.includes('--check')) {
        const d = differences(gen);
        if (d.length) { console.error(`core/dist/{AGENTS.md,llms.txt,llms-full.txt} are out of date (${d.length} differences); run node scripts/build-agent-refs.mjs\n${d.join('\n')}`); process.exit(1); }
        console.log(`core/dist/{${OUT_NAMES.join(',')}} match their sources`);
    } else {
        const n = write(gen);
        build({ write: true }); // the SRI manifest lists these files too, so rebuild it now that they are on disk
        console.log(`${n} agent reference files written to core/dist; dist/manifest.json refreshed`);
    }
}
