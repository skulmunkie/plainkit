// ONE command that runs what CI runs, in the same groups, so a failure reproduces locally with the same message. Node only, no dependencies.
//
//   node scripts/verify.mjs                  everything CI runs on a pull request except the browser and pack jobs (lint + node + dotnet)
//   node scripts/verify.mjs --fast           bootstrap + changelog + node tests (the inner loop)
//   node scripts/verify.mjs --no-dotnet      skip dotnet build + test
//   node scripts/verify.mjs --browser        also the in-browser element suite (node scripts/attest-browser.mjs, needs Chrome or Edge, about 3 minutes)
//   node scripts/verify.mjs --pack           also dotnet pack + node scripts/check-package.mjs
//   node scripts/verify.mjs --only node      one CI job: a group (lint, node, dotnet, browser, pack) or a check id (see --list); what it needs runs too
//   node scripts/verify.mjs --list           the checks, their groups and what each fix is
//   --base <ref>   the pull request's base (default: origin/main when it exists; CI passes GITHUB_BASE_REF). Without one the checks that compare
//                  against the base (changelog-pr, release-*) are skipped, and the output says so.
//   --verbose      print the full output of every check, not only of failed ones
//
// Each check prints one line (name, seconds, ok/FAIL/skip); a failed one adds the first useful lines of its output and a `FIX:` line. Exit code 1 when
// any check failed, 2 for a bad argument. The checks run in parallel where they are independent (the cheap ones first; everything that reads generated
// files waits for the bootstrap). The FIX messages are the table CHECKS below: AGENTS.md ("When CI fails") shows the same table, generated by
// `node scripts/verify.mjs --update-docs` and compared by scripts/tests/verify.test.mjs.
//
// Also (used by ci.yml): `--budget <group>` appends "job seconds against its budget" to the job summary; with GITHUB_OUTPUT set a failed run writes
// its failures (`failures=<json>`) for the "CI summary" job, and with GITHUB_STEP_SUMMARY set it writes a timing table.
