export const USAGE = `usage: node scripts/verify.mjs [--fast] [--no-dotnet] [--browser] [--pack] [--only <group|check>[,...]] [--base <ref>] [--verbose] [--list]
groups: ${GROUPS.join(', ')}   (node scripts/verify.mjs --list shows the checks)`;

/** Parses argv. Returns { opts, errors }. */
export function parseArgs(argv) {
    const opts = { fast: false, noDotnet: false, browser: false, pack: false, only: [], base: null, verbose: false, list: false, budget: null, fixTable: false, updateDocs: false, help: false };
    const errors = [];
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        const value = () => { const v = argv[i + 1]; if (v === undefined || v.startsWith('--')) { errors.push(`${a} needs a value`); return null; } i++; return v; };
        if (a === '--fast') opts.fast = true;
        else if (a === '--no-dotnet') opts.noDotnet = true;
        else if (a === '--browser') opts.browser = true;
        else if (a === '--pack') opts.pack = true;
        else if (a === '--verbose') opts.verbose = true;
        else if (a === '--list') opts.list = true;
        else if (a === '--fix-table') opts.fixTable = true;
        else if (a === '--update-docs') opts.updateDocs = true;
        else if (a === '--help' || a === '-h') opts.help = true;
        else if (a === '--only') { const v = value(); if (v) opts.only.push(...v.split(',').map(s => s.trim()).filter(Boolean)); }
        else if (a === '--base') opts.base = value();
        else if (a === '--budget') opts.budget = value();
        else errors.push(`unknown argument ${a}`);
    }
    const known = new Set([...GROUPS, ...CHECKS.map(c => c.id)]);
    for (const o of opts.only) if (!known.has(o)) errors.push(`--only ${o}: not a group or check (groups: ${GROUPS.join(', ')}; checks: ${CHECKS.map(c => c.id).join(', ')})`);
    if (opts.budget && !JOBS[opts.budget]) errors.push(`--budget ${opts.budget}: not a group (${GROUPS.join(', ')})`);
    if (opts.fast && opts.only.length) errors.push('use either --fast or --only, not both');
    return { opts, errors };
}

/** The checks to run, in table order, including what they need. Pure. */
export function selectChecks(opts, checks = CHECKS) {
    let picked;
    if (opts.only.length) picked = checks.filter(c => opts.only.includes(c.group) || opts.only.includes(c.id));
    else if (opts.fast) picked = checks.filter(c => c.fast);
    else {
        const groups = new Set(DEFAULT_GROUPS);
        if (opts.noDotnet) groups.delete('dotnet');
        if (opts.browser) groups.add('browser');
        if (opts.pack) groups.add('pack');
        picked = checks.filter(c => groups.has(c.group));
    }
    const ids = new Set(picked.map(c => c.id));
    const add = id => { if (ids.has(id)) return; ids.add(id); checks.find(c => c.id === id)?.needs.forEach(add); };
    picked.forEach(c => c.needs.forEach(add));
    return checks.filter(c => ids.has(c.id));
}

// ---------- output helpers (pure) ----------

const ANSI = /\[[0-9;]*[A-Za-z]/g;
export const stripAnsi = s => String(s).replace(ANSI, '');
export const seconds = ms => `${(ms / 1000).toFixed(1)} s`;

/** The first useful lines of a failed check's output: the "failing tests" list, else the first error-looking line with a line of context, else the start. */
export function usefulLines(text, { maxLines = 14, maxChars = 1500 } = {}) {
    const lines = stripAnsi(text).split(/\r?\n/);
    const find = re => lines.findIndex(l => re.test(l));
    let start = find(/^\s*(✖\s*)?failing tests:/i);
    if (start < 0) { const e = find(/(✖|^\s*not ok |\bFAIL(ED)?\b|\bFailed\b|\berror\s+[A-Z]+\d+|\berror:|\bError:|\bcheck-package:|\bnot right)/); if (e >= 0) start = Math.max(0, e - 1); }
    if (start < 0) start = Math.max(0, lines.findIndex(l => l.trim()));
    const out = lines.slice(start).filter(l => !/^\s+at .*(node:|node_modules)/.test(l) && l.trim() !== '').slice(0, maxLines).map(l => (l.length > 170 ? `${l.slice(0, 170)} ...` : l.trimEnd()));
    let text2 = out.join('\n').trim();
    if (text2.length > maxChars) text2 = `${text2.slice(0, maxChars)} ...`;
    return text2;
}

/** The generated "When CI fails" table (markdown), from the CHECKS table. */
export function fixTable(checks = CHECKS) {
    const cell = s => String(s).replaceAll('|', '\\|');
    return ['| Failing check | Likely cause | Fix |', '| --- | --- | --- |',
        ...checks.map(c => `| \`${c.id}\` (${c.group === 'setup' ? 'every job' : `job \`${c.group}\``}) | ${cell(c.cause)} | ${cell(c.fix)} |`)].join('\n');
}

/** AGENTS.md text with the region between the markers replaced by the current table (null when the markers are missing). */
export function withFixTable(text, checks = CHECKS) {
    const a = text.indexOf(TABLE_START), b = text.indexOf(TABLE_END);
    if (a < 0 || b < a) return null;
    return `${text.slice(0, a)}${TABLE_START}\n${fixTable(checks)}\n${text.slice(b)}`;
}

// ---------- base branch and release detection ----------

const git = (args, cwd = root) => spawnSync('git', args, { cwd, encoding: 'utf8' });

/** The base ref to compare against: --base, else the pull request's (GITHUB_BASE_REF), else origin/main when it exists locally; null in CI without one. */
export function resolveBase({ opts, env = process.env, cwd = root }) {
    if (opts.base) return opts.base;
    if (env.GITHUB_BASE_REF) return `origin/${env.GITHUB_BASE_REF}`;
    if (env.CI || env.GITHUB_ACTIONS) return null;
    return git(['rev-parse', '--verify', '--quiet', 'origin/main'], cwd).status === 0 ? 'origin/main' : null;
}

/** True when core/VERSION differs from the base's (and the base had one): a release pull request. */
export function isReleasePr(base, cwd = root) {
    if (!base) return false;
    if (git(['cat-file', '-e', `${base}:core/VERSION`], cwd).status !== 0) return false;
    return git(['diff', '--quiet', base, '--', 'core/VERSION'], cwd).status !== 0;
}

// ---------- in-process checks ----------

async function releaseFragments(ctx) {
    if (!ctx.base) return { skip: 'no base branch: pass --base <ref>' };
    if (!isReleasePr(ctx.base, ctx.root)) return { ok: true, output: 'not a release pull request' };
    const dir = path.join(ctx.root, 'changelog', 'unreleased');
    const left = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f !== '.gitkeep') : [];
    return left.length ? { ok: false, output: `core/VERSION changed (a release pull request) but fragments are left:\n${left.join('\n')}` } : { ok: true, output: 'release pull request: no fragments left' };
}

async function releasePr(ctx) {
    if (!ctx.base) return { skip: 'no base branch: pass --base <ref>' };
    const show = git(['show', `${ctx.base}:core/site/scorecard/api.baseline.json`], ctx.root);
    if (show.status !== 0) return { skip: `${ctx.base} has no API baseline` };
    const baseline = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'pk-baseline-')), 'base-baseline.json');
    fs.writeFileSync(baseline, show.stdout);
    let output = '';
    const step = async args => { const r = await runCmd([NODE, ...args], ctx.root); output += `$ node ${args.join(' ')}\n${r.out}`; return r.code === 0; };
    if (isReleasePr(ctx.base, ctx.root)) {
        output += 'core/VERSION changed: this is a release pull request\n';
        const a = await step(['core/tools/versioning.mjs', 'check', '--release']);
        const b = await step(['core/tools/versioning.mjs', 'bump', '--baseline', baseline, '--require']);
        return { ok: a && b, output };
    }
    output += 'core/VERSION unchanged: not a release pull request (information only)\n';
    return { ok: await step(['core/tools/versioning.mjs', 'bump', '--baseline', baseline]), output };
}

// CI runs `node scripts/generated.mjs check`. On a machine with uncommitted edits that command always fails ("the bootstrap changed tracked files"),
// so there the check compares against the state before the bootstrap instead.
async function generatedTree(ctx) {
    if (!ctx.dirtyBefore.length) {
        const r = await runCmd([NODE, 'scripts/generated.mjs', 'check'], ctx.root);
        return { ok: r.code === 0, output: r.out };
    }
    const problems = [];
    const tracked = git(['ls-files'], ctx.root).stdout.split('\n').filter(Boolean).filter(isGenerated);
    if (tracked.length) problems.push(`${tracked.length} generated file(s) are tracked by git (first: ${tracked[0]})`);
    const now = git(['status', '--porcelain', '--untracked-files=no'], ctx.root).stdout.split('\n').filter(Boolean);
    const before = new Set(ctx.dirtyBefore);
    const changed = now.filter(l => !before.has(l));
    if (changed.length) problems.push(`the bootstrap changed ${changed.length} tracked file(s) (first: ${changed[0].trim()})`);
    return problems.length ? { ok: false, output: `Bootstrap does not leave the tree clean:\n- ${problems.join('\n- ')}` }
        : { ok: true, output: 'no generated path is tracked; the bootstrap changed nothing (your uncommitted edits were there before it ran)' };
}

async function packCheck(ctx) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pk-pack-'));
    try {
        const p = await runCmd(['dotnet', 'pack', 'blazor/src/PlainKit.Blazor', '-c', 'Release', '-o', dir, '--nologo'], ctx.root);
        if (p.code !== 0) return { ok: false, output: p.out };
        const c = await runCmd([NODE, 'scripts/check-package.mjs', dir], ctx.root);
        return { ok: c.code === 0, output: c.out };
    } finally { fs.rmSync(dir, { recursive: true, force: true }); }
}

// ---------- running ----------

/** Runs a command, resolves { code, out } with stdout and stderr interleaved as they arrived. Never rejects. */
export function runCmd(cmd, cwd = root, env = process.env) {
    return new Promise(resolve => {
        let out = '';
        let child;
        try { child = spawn(cmd[0], cmd.slice(1), { cwd, env, windowsHide: true }); } catch (e) { resolve({ code: 127, out: `${e.message}\n` }); return; }
        child.stdout.on('data', d => { out += d; });
        child.stderr.on('data', d => { out += d; });
        child.on('error', e => { out += `${e.message}\n`; resolve({ code: 127, out }); });
        child.on('close', code => resolve({ code: code ?? 1, out }));
    });
}

async function runOne(check, ctx) {
    const t = performance.now();
    try {
        if (check.fn) {
            const r = await check.fn(ctx);
            if (r.skip) return { status: 'skip', ms: performance.now() - t, reason: r.skip, out: '' };
            return { status: r.ok ? 'ok' : 'FAIL', ms: performance.now() - t, out: r.output ?? '' };
        }
        const cmd = check.cmd(ctx);
        if (!Array.isArray(cmd)) return { status: 'skip', ms: performance.now() - t, reason: cmd.skip, out: '' };
        const r = await runCmd(cmd, ctx.root);
        return { status: r.code === 0 ? 'ok' : 'FAIL', ms: performance.now() - t, out: r.out };
    } catch (e) { return { status: 'FAIL', ms: performance.now() - t, out: `${e.stack || e}` }; }
}

/** Runs the selected checks in parallel, each after the checks it needs. `onDone(check, result)` is called as each finishes. Returns the results in table order. */
export async function runChecks(selected, ctx, onDone = () => {}) {
    const started = new Map();
    const start = check => {
        if (started.has(check.id)) return started.get(check.id);
        const p = (async () => {
            const pick = id => selected.find(c => c.id === id);
            const deps = await Promise.all(check.needs.filter(pick).map(id => start(pick(id))));
            await Promise.all((check.after ?? []).filter(pick).map(id => start(pick(id))));
            const blocked = deps.find(d => d.status !== 'ok');
            const result = blocked ? { status: 'skip', ms: 0, reason: 'a check it needs failed', out: '' } : await runOne(check, ctx);
            result.check = check;
            onDone(check, result);
            return result;
        })();
        started.set(check.id, p);
        return p;
    };
    return Promise.all(selected.map(start));
}

export function formatResult(check, r, { verbose = false, ci = false } = {}) {
    const pad = check.id.padEnd(18);
    if (r.status === 'skip') return `skip  ${pad} ${r.reason}`;
    const lines = [`${r.status === 'ok' ? 'ok   ' : 'FAIL '} ${pad} ${seconds(r.ms)}`];
    if (r.status === 'FAIL') {
        const ex = usefulLines(r.out);
        if (ex) lines.push(...ex.split('\n').map(l => `      ${l}`));
        lines.push(`FIX: ${check.fix}`);
        if (ci) lines.push(`::group::full output of ${check.id}`, stripAnsi(r.out).trimEnd(), '::endgroup::');
    } else if (verbose && r.out.trim()) lines.push(...stripAnsi(r.out).trimEnd().split('\n').map(l => `      ${l}`));
    return lines.join('\n');
}

/** The failures for the CI summary job: [{ id, name, fix, excerpt }]. */
export const failuresOf = results => results.filter(r => r.status === 'FAIL').map(r => ({ id: r.check.id, name: r.check.name, fix: r.check.fix, excerpt: usefulLines(r.out, { maxChars: 900 }) }));

const escapeAnnotation = s => String(s).replace(/%/g, '%25').replace(/\r/g, '%0D').replace(/\n/g, '%0A');

function writeCiFiles(results, totalMs, label, env = process.env) {
    const failures = failuresOf(results);
    if (env.GITHUB_OUTPUT && failures.length) fs.appendFileSync(env.GITHUB_OUTPUT, `failures=${JSON.stringify(failures)}\n`);
    for (const f of failures) if (env.GITHUB_ACTIONS) console.log(`::error title=${escapeAnnotation(`verify ${f.name} failed`)}::${escapeAnnotation(f.fix)}`);
    if (env.GITHUB_STEP_SUMMARY) {
        const rows = results.map(r => `| ${r.check.id} | ${r.status === 'skip' ? `skip: ${r.reason}` : r.status} | ${r.status === 'skip' ? '' : seconds(r.ms)} |`);
        fs.appendFileSync(env.GITHUB_STEP_SUMMARY, `#### ${label}\n\n| Check | Result | Time |\n| --- | --- | --- |\n${rows.join('\n')}\n\nTotal ${seconds(totalMs)}.\n\n`);
    }
}

export async function main(argv, env = process.env) {
    const { opts, errors } = parseArgs(argv);
    if (opts.help) { console.log(USAGE); return 0; }
    if (errors.length) { console.error(`verify: ${errors.join('\nverify: ')}\n${USAGE}`); return 2; }
    if (opts.list) { for (const c of CHECKS) console.log(`${c.id.padEnd(18)} ${String(c.group).padEnd(8)} ${c.fast ? 'fast ' : '     '} ${c.fix}`); return 0; }
    if (opts.fixTable) { console.log(fixTable()); return 0; }
    if (opts.updateDocs) {
        const file = path.join(root, 'AGENTS.md');
        const next = withFixTable(fs.readFileSync(file, 'utf8'));
        if (next === null) { console.error(`verify: AGENTS.md has no ${TABLE_START} ... ${TABLE_END} region`); return 1; }
        fs.writeFileSync(file, next);
        console.log('AGENTS.md: the "When CI fails" table is current');
        return 0;
    }
    if (opts.budget) {
        const t0 = Number(env.PK_JOB_START);
        if (!t0) { console.error('verify: --budget needs PK_JOB_START (epoch seconds, set by the job\'s first step)'); return 2; }
        const note = budgetNote(`${JOBS[opts.budget].name} job`, Date.now() / 1000 - t0, JOBS[opts.budget].budget);
        console.log(note);
        if (note.includes('WARNING') && env.GITHUB_ACTIONS) console.log(`::warning title=time budget::${escapeAnnotation(note.split('\n')[1])}`);
        if (env.GITHUB_STEP_SUMMARY) fs.appendFileSync(env.GITHUB_STEP_SUMMARY, `${note}\n\n`);
        return 0;
    }

    const selected = selectChecks(opts);
    const base = resolveBase({ opts, env });
    const dirtyBefore = git(['status', '--porcelain', '--untracked-files=no']).stdout.split('\n').filter(Boolean);
    const ctx = { root, base, dirtyBefore };
    const ci = Boolean(env.GITHUB_ACTIONS);
    const t0 = performance.now();
    console.log(`verify: ${selected.map(c => c.id).join(', ')}${base ? ` (base ${base})` : ''}`);
    const results = await runChecks(selected, ctx, (check, r) => console.log(formatResult(check, r, { verbose: opts.verbose, ci })));
    const total = performance.now() - t0;
    const count = s => results.filter(r => r.status === s).length;
    console.log(`\nverify: ${count('ok')} ok, ${count('FAIL')} failed, ${count('skip')} skipped in ${seconds(total)}`);
    const label = opts.only.length ? `verify --only ${opts.only.join(',')}` : opts.fast ? 'verify --fast' : 'verify';
    writeCiFiles(results, total, label, env);
    if (count('FAIL')) {
        console.log(`Reproduce one check: node scripts/verify.mjs --only ${results.find(r => r.status === 'FAIL').check.id}`);
        return 1;
    }
    return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(await main(process.argv.slice(2)));
